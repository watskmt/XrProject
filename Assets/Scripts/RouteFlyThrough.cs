        new double2(135.517968, 34.697000),
        new double2(135.501499, 34.698086),
    };

    int _segment;
    double _distIntoSegment;   // meters advanced into the current segment
    float _currentHeight;      // ellipsoid height currently set on the georeference origin
    float _yVel;
    bool _hasSurface;

    void Awake()
    {
        if (georeference == null)
            georeference = GetComponentInParent<CesiumGeoreference>();
        if (georeference == null)
            georeference = FindObjectOfType<CesiumGeoreference>();

        // Rough starting height (~20 m above Nihonbashi ground); the raycast feedback refines it.
        _currentHeight = 60f;
        if (georeference != null)
            georeference.SetOriginLongitudeLatitudeHeight(k_Route[0].x, k_Route[0].y, _currentHeight);
    }

    void Update()
    {
        if (georeference == null) return;

        // --- Hold a constant clearance above the surface (feedback via downward raycast) ---
        var rayStart = new Vector3(0f, raycastStartHeight, 0f);
        if (Physics.Raycast(rayStart, Vector3.down, out var hit, raycastStartHeight * 2f))
        {
            // Ground world Y = G - currentHeight, so this drives currentHeight toward G + clearance.
            float targetH = _currentHeight + (hit.point.y + heightAboveSurfaceMeters);
            _currentHeight = _hasSurface
                ? Mathf.SmoothDamp(_currentHeight, targetH, ref _yVel, heightSmoothTime)
                : targetH;
            _hasSurface = true;
        }

        // --- Advance along the route polyline ---
        _distIntoSegment += speedMetersPerSecond * Time.deltaTime;
        double segLen = SegmentLengthMeters(_segment);
        while (_distIntoSegment >= segLen)
        {
            _distIntoSegment -= segLen;
            if (_segment >= k_Route.Length - 2)
            {
                if (loop) { _segment = 0; }
                else { _distIntoSegment = 0; break; } // arrived at Osaka; hold position
            }
            else
            {
                _segment++;
            }
            segLen = SegmentLengthMeters(_segment);
        }

        double f = segLen > 0 ? _distIntoSegment / segLen : 0;
        double2 a = k_Route[_segment];
        double2 b = k_Route[_segment + 1];
        double2 cur = a + (b - a) * f;
        double2 ahead = a + (b - a) * math.min(1.0, f + 0.05);

        // --- Move the georeference origin to the current position ---
        georeference.SetOriginLongitudeLatitudeHeight(cur.x, cur.y, _currentHeight);

        // --- Face the direction of travel (kept horizontal) ---
        double3 aheadEcef = CesiumWgs84Ellipsoid.LongitudeLatitudeHeightToEarthCenteredEarthFixed(
            new double3(ahead.x, ahead.y, _currentHeight));
        double3 aheadUnity = georeference.TransformEarthCenteredEarthFixedPositionToUnity(aheadEcef);
        var dir = new Vector3((float)aheadUnity.x, 0f, (float)aheadUnity.z);
        if (dir.sqrMagnitude > 1e-6f)
            transform.rotation = Quaternion.LookRotation(dir.normalized, Vector3.up);
    }

    double SegmentLengthMeters(int i) => HaversineMeters(k_Route[i], k_Route[i + 1]);

    static double HaversineMeters(double2 lonLatA, double2 lonLatB)
    {
        const double R = 6371000.0;
        double lat1 = math.radians(lonLatA.y), lat2 = math.radians(lonLatB.y);
        double dLat = lat2 - lat1;
        double dLon = math.radians(lonLatB.x - lonLatA.x);
        double h = math.sin(dLat / 2) * math.sin(dLat / 2)
                 + math.cos(lat1) * math.cos(lat2) * math.sin(dLon / 2) * math.sin(dLon / 2);
        return 2.0 * R * math.asin(math.min(1.0, math.sqrt(h)));
    }
